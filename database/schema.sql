CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 login VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','manager') NOT NULL DEFAULT 'manager',
 active TINYINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS web_sessions (
 id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 payload MEDIUMBLOB NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL,
 INDEX(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stored_uploads (
 filename VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 mime VARCHAR(40) NOT NULL,
 contents MEDIUMBLOB NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS user_permissions (
 user_id INT UNSIGNED NOT NULL,
 section VARCHAR(30) NOT NULL,
 PRIMARY KEY(user_id,section),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS furniture_types (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title_ru VARCHAR(180) NOT NULL, title_en VARCHAR(180) NOT NULL,
 body_ru MEDIUMTEXT NOT NULL, body_en MEDIUMTEXT NOT NULL,
 image VARCHAR(250) NOT NULL DEFAULT '',
 sort_order INT NOT NULL DEFAULT 0, published TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS furniture_subtypes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, type_id INT UNSIGNED NOT NULL,
 title_ru VARCHAR(180) NOT NULL, title_en VARCHAR(180) NOT NULL,
 body_ru MEDIUMTEXT NOT NULL, body_en MEDIUMTEXT NOT NULL,
 image VARCHAR(250) NOT NULL DEFAULT '',
 sort_order INT NOT NULL DEFAULT 0, published TINYINT NOT NULL DEFAULT 1,
 FOREIGN KEY(type_id) REFERENCES furniture_types(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS designers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title_ru VARCHAR(180) NOT NULL, title_en VARCHAR(180) NOT NULL,
 body_ru MEDIUMTEXT NOT NULL, body_en MEDIUMTEXT NOT NULL,
 image VARCHAR(250) NOT NULL DEFAULT '',
 sort_order INT NOT NULL DEFAULT 0, published TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, subtype_id INT UNSIGNED NOT NULL, designer_id INT UNSIGNED NULL,
 title_ru VARCHAR(180) NOT NULL, title_en VARCHAR(180) NOT NULL,
 body_ru MEDIUMTEXT NOT NULL, body_en MEDIUMTEXT NOT NULL,
 price_minor INT UNSIGNED NOT NULL,
 image VARCHAR(250) NOT NULL DEFAULT '',
 sort_order INT NOT NULL DEFAULT 0, published TINYINT NOT NULL DEFAULT 1,
 FOREIGN KEY(subtype_id) REFERENCES furniture_subtypes(id),
 FOREIGN KEY(designer_id) REFERENCES designers(id) ON DELETE SET NULL,
 INDEX(published,subtype_id), CHECK(price_minor>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS articles (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, kind ENUM('news','promotion','page') NOT NULL,
 slug VARCHAR(120) NOT NULL UNIQUE,
 title_ru VARCHAR(180) NOT NULL, title_en VARCHAR(180) NOT NULL,
 body_ru MEDIUMTEXT NOT NULL, body_en MEDIUMTEXT NOT NULL,
 publish_date DATE NOT NULL,
 image VARCHAR(250) NOT NULL DEFAULT '',
 sort_order INT NOT NULL DEFAULT 0, published TINYINT NOT NULL DEFAULT 1,
 INDEX(kind,published,publish_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS gallery (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 entity ENUM('types','products') NOT NULL, entity_id INT UNSIGNED NOT NULL,
 path VARCHAR(250) NOT NULL,
 sort_order INT NOT NULL DEFAULT 0,
 INDEX(entity,entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS contacts (
 id INT UNSIGNED PRIMARY KEY,
 company_ru VARCHAR(180) NOT NULL, company_en VARCHAR(180) NOT NULL,
 address_ru VARCHAR(250) NOT NULL, address_en VARCHAR(250) NOT NULL,
 phone VARCHAR(30) NOT NULL, email VARCHAR(190) NOT NULL,
 latitude DECIMAL(10,7) NOT NULL, longitude DECIMAL(10,7) NOT NULL,
 hours_ru VARCHAR(180) NOT NULL, hours_en VARCHAR(180) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS orders (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 reference CHAR(32) NOT NULL UNIQUE, submission_key CHAR(32) NOT NULL UNIQUE,
 customer_name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(30) NOT NULL,
 address VARCHAR(250) NOT NULL, comment TEXT NOT NULL,
 language ENUM('ru','en') NOT NULL DEFAULT 'ru',
 status ENUM('new','confirmed','completed','cancelled') NOT NULL DEFAULT 'new',
 subtotal_minor BIGINT UNSIGNED NOT NULL, delivery_minor INT UNSIGNED NOT NULL,
 total_minor BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id INT UNSIGNED NOT NULL,
 product_id INT UNSIGNED NULL, title VARCHAR(180) NOT NULL,
 quantity SMALLINT UNSIGNED NOT NULL, unit_price_minor INT UNSIGNED NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL,
 CHECK(quantity BETWEEN 1 AND 20)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mail_outbox (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id INT UNSIGNED NOT NULL UNIQUE,
 status ENUM('pending','sent','failed') NOT NULL DEFAULT 'pending',
 attempts INT UNSIGNED NOT NULL DEFAULT 0, last_error VARCHAR(500) NULL,
 sent_at DATETIME NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
